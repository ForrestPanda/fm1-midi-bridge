"""Generate the ATT database for the BLE MIDI service in the format the JieLi
btstack expects (same as BTstack's compile_gatt.py output): a byte array of
attributes, each [size u16][flags u16][handle u16][uuid 16|128][value...],
terminated by a zero u16.

  gatt_midi.py OUT.h [--name NAME]

Attributes:
  0x0001 PRIMARY_SERVICE  1800 (GAP)
  0x0002 CHARACTERISTIC   2a00 Device Name, READ | DYNAMIC
  0x0003   value
  0x0004 PRIMARY_SERVICE  1801 (GATT)
  0x0005 PRIMARY_SERVICE  03B80E5A-EDE8-4B33-A751-6CE34EC4C700 (MIDI)
  0x0006 CHARACTERISTIC   7772E5DB-3868-4112-A1A9-F2669D106BF3
                          READ | WRITE_WITHOUT_RESPONSE | NOTIFY | DYNAMIC
  0x0007   value
  0x0008   CLIENT_CHARACTERISTIC_CONFIGURATION, READ | WRITE | DYNAMIC
"""
import struct
import sys

# BTstack att.h property / flag bits
BROADCAST, READ, WRITE_WITHOUT_RESPONSE, WRITE, NOTIFY, INDICATE = 0x01, 0x02, 0x04, 0x08, 0x10, 0x20
DYNAMIC, UUID128 = 0x100, 0x200

MIDI_SERVICE = "03B80E5A-EDE8-4B33-A751-6CE34EC4C700"
MIDI_CHAR = "7772E5DB-3868-4112-A1A9-F2669D106BF3"


def uuid_bytes(u):
    if isinstance(u, int):
        return struct.pack("<H", u)
    return bytes.fromhex(u.replace("-", ""))[::-1]   # 128-bit, little endian


def attr(flags, handle, uuid, value=b""):
    ub = uuid_bytes(uuid)
    if len(ub) == 16:
        flags |= UUID128
    body = struct.pack("<HH", flags, handle) + ub + value
    return struct.pack("<H", len(body) + 2) + body


def primary_service(handle, uuid):
    return attr(READ, handle, 0x2800, uuid_bytes(uuid))


def characteristic(handle, uuid, props, flags):
    """declaration at handle, value at handle+1; returns (bytes, next_handle)"""
    decl_val = bytes([props & 0xFF]) + struct.pack("<H", handle + 1) + uuid_bytes(uuid)
    out = attr(READ, handle, 0x2803, decl_val)
    out += attr(flags | (props & 0xFF), handle + 1, uuid)
    return out, handle + 2


def cccd(handle):
    return attr(READ | WRITE | DYNAMIC, handle, 0x2902, b"\0\0")


def build():
    db = b""
    db += primary_service(0x0001, 0x1800)
    c, h = characteristic(0x0002, 0x2A00, READ, DYNAMIC)
    db += c
    db += primary_service(0x0004, 0x1801)
    db += primary_service(0x0005, MIDI_SERVICE)
    c, h = characteristic(0x0006, MIDI_CHAR, READ | WRITE_WITHOUT_RESPONSE | NOTIFY, DYNAMIC)
    db += c
    db += cccd(0x0008)
    db += b"\0\0"
    return db


def parse(db):
    """decode back for checking"""
    out, i = [], 0
    while i + 2 <= len(db):
        size = struct.unpack_from("<H", db, i)[0]
        if size == 0:
            break
        flags, handle = struct.unpack_from("<HH", db, i + 2)
        ul = 16 if flags & UUID128 else 2
        uuid = db[i + 6:i + 6 + ul][::-1].hex()
        value = db[i + 6 + ul:i + size]
        out.append((handle, flags, uuid, value.hex()))
        i += size
    return out


def emit(path, db):
    lines = ["/* SPDX-License-Identifier: MIT */",
             "/* Generated by tools/gatt_midi.py: do not edit. BLE MIDI 1.0 ATT database",
             " * in the JieLi/BTstack format (size, flags, handle, uuid, value). */",
             "#pragma once", "#include <stdint.h>", "",
             "static const uint8_t midi_profile_data[] = {"]
    for handle, flags, uuid, value in parse(db):
        lines.append(f"    // 0x{handle:04x} uuid {uuid} flags 0x{flags:03x}")
    rows = [db[i:i + 12] for i in range(0, len(db), 12)]
    for r in rows:
        lines.append("    " + ", ".join(f"0x{b:02x}" for b in r) + ",")
    lines += ["};", "",
              "#define ATT_HANDLE_GAP_DEVICE_NAME_VALUE        0x0003",
              "#define ATT_HANDLE_MIDI_IO_VALUE                0x0007",
              "#define ATT_HANDLE_MIDI_IO_CLIENT_CONFIGURATION 0x0008", ""]
    with open(path, "w") as f:
        f.write("\n".join(lines))


if __name__ == "__main__":
    if len(sys.argv) < 2:
        sys.exit(__doc__)
    db = build()
    emit(sys.argv[1], db)
    for row in parse(db):
        print("handle 0x%04x flags 0x%03x uuid %s value %s" % row)
