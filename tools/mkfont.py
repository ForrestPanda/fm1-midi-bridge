"""Render a monospace TTF into a 1-bpp bitmap font header for the panel.

  mkfont.py OUT.h [--ttf PATH] [--size PX] [--w W --h H] [--name PREFIX]

Default: DejaVu Sans Mono (Bitstream Vera license; its notice goes into the header) at a cell of
8 x 14 pixels, ASCII 0x20..0x7E. Each glyph is H rows of one byte (uint16_t when
W > 8), MSB = left pixel. --name sets the macro and table prefix (FONT / font_glyphs
by default; the Perform page's 16 x 28 font is FONT_BIG / font_big_glyphs:
  mkfont.py app/ui/font_big.h --size 24 --w 16 --h 28 --name BIG).
"""
import argparse
from PIL import Image, ImageDraw, ImageFont

ap = argparse.ArgumentParser()
ap.add_argument("out")
ap.add_argument("--ttf", default="/usr/share/fonts/truetype/dejavu/DejaVuSansMono.ttf")
ap.add_argument("--size", type=int, default=13)
ap.add_argument("--w", type=int, default=8)
ap.add_argument("--h", type=int, default=14)
ap.add_argument("--name", default="", help="prefix: FONT_<NAME>_W and font_<name>_glyphs")
a = ap.parse_args()
MAC = "FONT_%s" % a.name.upper() if a.name else "FONT"
TAB = "font_%s_glyphs" % a.name.lower() if a.name else "font_glyphs"
TYPE, FMT, TOP = ("uint16_t", "0x%04x", 0x8000) if a.w > 8 else ("uint8_t", "0x%02x", 0x80)

font = ImageFont.truetype(a.ttf, a.size)
asc, desc = font.getmetrics()
rows = []
for c in range(0x20, 0x7F):
    img = Image.new("1", (a.w, a.h), 0)
    d = ImageDraw.Draw(img)
    # centre the glyph box horizontally, baseline at asc
    bbox = font.getbbox(chr(c))
    gw = bbox[2] - bbox[0]
    x = (a.w - gw) // 2 - bbox[0] if gw <= a.w else -bbox[0]
    y = (a.h - (asc + desc)) // 2
    d.text((x, y), chr(c), font=font, fill=1)
    px = img.load()
    glyph = []
    for yy in range(a.h):
        b = 0
        for xx in range(a.w):
            if px[xx, yy]:
                b |= TOP >> xx
        glyph.append(b)
    rows.append((c, glyph))

with open(a.out, "w") as f:
    f.write("/* SPDX-License-Identifier: Bitstream-Vera */\n"
            "/* Generated by tools/mkfont.py from %s at %d px: do not edit.\n"
            " * Bitmaps of DejaVu Sans Mono glyphs, a modified copy of the Bitstream Vera font\n"
            " * software; the font's own notice, which must stay with every copy (LICENSES/Bitstream-Vera.txt):\n"
            " *\n"
            " * Copyright (c) 2003 by Bitstream, Inc. All Rights Reserved.\n"
            " * Bitstream Vera is a trademark of Bitstream, Inc.\n"
            " * DejaVu changes are in public domain.\n"
            " *\n"
            " * Permission is hereby granted, free of charge, to any person obtaining a copy of the\n"
            " * fonts accompanying this license (\"Fonts\") and associated documentation files (the\n"
            " * \"Font Software\"), to reproduce and distribute the Font Software, including without\n"
            " * limitation the rights to use, copy, merge, publish, distribute, and/or sell copies of\n"
            " * the Font Software, and to permit persons to whom the Font Software is furnished to do\n"
            " * so, subject to the following conditions: the above copyright and trademark notices\n"
            " * and this permission notice shall be included in all copies of one or more of the Font\n"
            " * Software typefaces; the Font Software may be modified only if the fonts are renamed to\n"
            " * names not containing either the words \"Bitstream\" or the word \"Vera\"; no copy of one\n"
            " * or more of the Font Software typefaces may be sold by itself. THE FONT SOFTWARE IS\n"
            " * PROVIDED \"AS IS\", WITHOUT WARRANTY OF ANY KIND. The full text: LICENSES/Bitstream-Vera.txt. */\n"
            "#pragma once\n#include <stdint.h>\n\n" % (a.ttf.split('/')[-1], a.size))
    f.write("#define %s_W %d\n#define %s_H %d\n#define %s_FIRST 0x20\n#define %s_LAST 0x7E\n\n" % (MAC, a.w, MAC, a.h, MAC, MAC))
    f.write("static const %s %s[%d][%s_H] = {\n" % (TYPE, TAB, len(rows), MAC))
    for c, g in rows:
        f.write("    {%s}, /* %s */\n" % (", ".join(FMT % b for b in g), chr(c) if chr(c) != '*' and chr(c) != '/' else ' '))
    f.write("};\n")
# preview a few glyphs
for c, g in rows:
    if chr(c) in "A9#":
        print(chr(c)); print("\n".join("".join("#" if b & (TOP >> x) else "." for x in range(a.w)) for b in g))
