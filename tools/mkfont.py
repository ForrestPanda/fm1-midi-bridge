"""Render a monospace TTF into a 1-bpp bitmap font header for the panel.

  mkfont.py OUT.h [--ttf PATH] [--size PX] [--w W --h H]

Default: DejaVu Sans Mono (Bitstream Vera license, free to embed) at a cell of
8 x 14 pixels, ASCII 0x20..0x7E. Each glyph is H rows of one byte, MSB = left pixel.
"""
import argparse
from PIL import Image, ImageDraw, ImageFont

ap = argparse.ArgumentParser()
ap.add_argument("out")
ap.add_argument("--ttf", default="/usr/share/fonts/truetype/dejavu/DejaVuSansMono.ttf")
ap.add_argument("--size", type=int, default=13)
ap.add_argument("--w", type=int, default=8)
ap.add_argument("--h", type=int, default=14)
a = ap.parse_args()

font = ImageFont.truetype(a.ttf, a.size)
asc, desc = font.getmetrics()
rows = []
for c in range(0x20, 0x7F):
    img = Image.new("1", (a.w, a.h), 0)
    d = ImageDraw.Draw(img)
    # centre the glyph box horizontally, baseline at asc
    bbox = font.getbbox(chr(c))
    gw = bbox[2] - bbox[0]
    x = (a.w - gw) // 2 - bbox[0] if gw <= a.w else -bbox[0]
    y = (a.h - (asc + desc)) // 2
    d.text((x, y), chr(c), font=font, fill=1)
    px = img.load()
    glyph = []
    for yy in range(a.h):
        b = 0
        for xx in range(a.w):
            if px[xx, yy]:
                b |= 0x80 >> xx
        glyph.append(b)
    rows.append((c, glyph))

with open(a.out, "w") as f:
    f.write("/* Generated by tools/mkfont.py from %s at %d px: do not edit.\n"
            " * DejaVu Sans Mono, Bitstream Vera Fonts license (free to embed). */\n"
            "#pragma once\n#include <stdint.h>\n\n" % (a.ttf.split('/')[-1], a.size))
    f.write("#define FONT_W %d\n#define FONT_H %d\n#define FONT_FIRST 0x20\n#define FONT_LAST 0x7E\n\n" % (a.w, a.h))
    f.write("static const uint8_t font_glyphs[%d][FONT_H] = {\n" % len(rows))
    for c, g in rows:
        f.write("    {%s}, /* %s */\n" % (", ".join("0x%02x" % b for b in g), chr(c) if chr(c) != '*' and chr(c) != '/' else ' '))
    f.write("};\n")
# preview a few glyphs
for c, g in rows:
    if chr(c) in "A9#":
        print(chr(c)); print("\n".join("".join("#" if b & (0x80 >> x) else "." for x in range(a.w)) for b in g))
